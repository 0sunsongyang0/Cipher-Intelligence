def _check_evidence_integrity(payload: dict[str, Any]) -> dict[str, Any]:
    evidence = payload.get("evidence")
    if not isinstance(evidence, list): raise HTTPException(status_code=422, detail="evidence 必须是对象数组")
    blockers, warnings, hashes = [], [], {}
    for index, raw in enumerate(evidence[:500]):
        if not isinstance(raw, dict): blockers.append({"index": index, "code": "invalid-item"}); continue
        label = raw.get("title") or raw.get("id") or index
        if raw.get("reviewStatus") != "verified": blockers.append({"evidence": label, "code": "not-verified"})
        content_hash = str(raw.get("contentHash") or "").strip().casefold()
        if not content_hash: blockers.append({"evidence": label, "code": "missing-hash"})
        else: hashes.setdefault(content_hash, []).append(label)
        if int(raw.get("confidence", 0) or 0) < 50: warnings.append({"evidence": label, "code": "low-confidence"})
        if int(raw.get("sourceTrust", 0) or 0) < 50: warnings.append({"evidence": label, "code": "low-source-trust"})
    duplicates = [{"hash": key, "evidence": values} for key, values in hashes.items() if len(values) > 1]
    warnings.extend({"code": "duplicate-hash", **item} for item in duplicates)
    return {"readyForSigning": bool(evidence) and not blockers, "evidenceCount": len(evidence),
            "blockers": blockers, "warnings": warnings, "duplicateHashes": duplicates}


def _review_capa_capabilities(payload: dict[str, Any]) -> dict[str, Any]:
    capabilities = _string_list(payload.get("capabilities"), limit=300)
    groups = {key: [] for key in ("execution", "persistence", "defense-evasion", "collection", "communication", "other")}
    patterns = {
        "execution": ("execute", "process", "shell", "command", "code"),
        "persistence": ("persist", "registry run", "service", "scheduled task", "startup"),
        "defense-evasion": ("inject", "obfuscat", "pack", "anti-debug", "delete", "disable"),
        "collection": ("capture", "keylog", "screenshot", "clipboard", "credential", "browser"),
        "communication": ("http", "dns", "socket", "download", "upload", "network", "c2"),
    }
    for capability in capabilities:
        lowered = capability.casefold()
        group = next((name for name, words in patterns.items() if any(word in lowered for word in words)), "other")
        groups[group].append(capability)
    high_signal = sum(len(groups[name]) for name in ("persistence", "defense-evasion", "collection", "communication"))
    risk = "high" if high_signal >= 4 else "medium" if high_signal else "low"
    checklist = ["在 CAPE 进程树中验证能力是否真实触发", "将高信号能力与原始样本哈希关联", "排除库代码和未达路径导致的静态误报"]
    return {"upstream": "mandiant/capa@v9.4.0", "risk": risk, "groups": groups,
            "capabilityCount": len(capabilities), "highSignalCount": high_signal,
            "reviewChecklist": checklist, "requiresHumanReview": True}


