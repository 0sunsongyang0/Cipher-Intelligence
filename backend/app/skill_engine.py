        output["iocs"] = [_lookup_ioc(str(value.get("value", "")), str(value.get("type") or _ioc_type(str(value.get("value", ""))))) if isinstance(value, dict) else _lookup_ioc(str(value), _ioc_type(str(value))) for value in values if str(value.get("value", "") if isinstance(value, dict) else value).strip()]
