def _map_attack(payload: dict[str, Any]) -> dict[str, Any]:
    behaviors = _string_list(payload.get("behaviors"))
    mappings, unmatched = [], []
    seen: set[tuple[str, str]] = set()
    for behavior in behaviors:
        lowered = behavior.casefold()
        matched = False
        for patterns, technique_id, name, tactic in ATTACK_PATTERNS:
            if any(pattern in lowered for pattern in patterns):
                key = (behavior, technique_id)
                if key not in seen:
                    mappings.append({"behavior": behavior, "techniqueId": technique_id, "technique": name,
                                     "tactic": tactic, "confidence": 75, "requiresHumanReview": True})
                    seen.add(key)
                matched = True
        if not matched: unmatched.append(behavior)
    return {"mappings": mappings, "unmatched": unmatched, "mappedCount": len(mappings),
            "coverage": round((len(behaviors) - len(unmatched)) * 100 / len(behaviors)) if behaviors else 0}


def _triage_phishing(payload: dict[str, Any]) -> dict[str, Any]:
    sender = str(payload.get("sender", "")).strip()
    subject = str(payload.get("subject", "")).strip()
    authentication = str(payload.get("authentication", "")).casefold()
    body = str(payload.get("body", "")).casefold()
    urls = _string_list(payload.get("urls", []))
    attachments = _string_list(payload.get("attachments", []))
    score, findings = 0, []
    def add(points: int, code: str, detail: str) -> None:
        nonlocal score
        score += points; findings.append({"code": code, "points": points, "detail": detail})
    if any(value in authentication for value in ("fail", "softfail", "none", "temperror")): add(25, "auth-failure", "SPF/DKIM/DMARC 认证异常")
    if any(word in f"{subject} {body}" for word in ("紧急", "urgent", "立即", "过期", "suspend")): add(15, "urgency", "存在紧迫或威胁性话术")
    if any(word in body for word in ("密码", "password", "验证码", "credential", "login")): add(20, "credential-request", "正文涉及凭据或登录请求")
    if urls: add(min(20, 5 + len(urls) * 3), "external-links", f"包含 {len(urls)} 个链接")
    dangerous = [name for name in attachments if name.casefold().endswith((".exe", ".js", ".vbs", ".scr", ".iso", ".lnk", ".docm", ".xlsm"))]
    if dangerous: add(30, "dangerous-attachment", f"高风险附件：{'、'.join(dangerous[:5])}")
    if sender and "@" not in sender: add(10, "sender-format", "发件人地址格式异常")
    score = min(100, score)
    risk = "critical" if score >= 75 else "high" if score >= 50 else "medium" if score >= 25 else "low"
    actions = ["保留原始邮件与完整邮件头", "对链接与附件进行隔离分析"]
    if score >= 50: actions[:0] = ["隔离邮件并检索其他收件人", "阻断已确认的恶意 IOC"]
    return {"sender": sender, "subject": subject, "score": score, "risk": risk, "findings": findings,
            "recommendedActions": actions, "requiresAnalystReview": True}


def _build_blocklist(payload: dict[str, Any]) -> dict[str, Any]:
    values = list(dict.fromkeys(value.strip().casefold() for value in _string_list(payload.get("indicators"), limit=500)))
    network, excluded = [], []
    for value in values:
        kind = _ioc_type(value)
        (excluded if kind == "sha256" else network).append({"type": kind, "value": value})
    ticket = str(payload.get("ticket", "")).strip()
    expires = max(1, min(8760, int(payload.get("expiresHours", 24) or 24)))
    header = ["# Cipher containment draft", f"# ticket: {ticket or 'not-provided'}", f"# expires-hours: {expires}", "# requires-change-approval: true"]
    content = "\n".join(header + [item["value"] for item in network]) + "\n"
    return {"format": "plain-network-blocklist", "content": content, "entries": network,
            "excluded": excluded, "entryCount": len(network), "expiresHours": expires,
            "validation": {"status": "draft", "requiresHumanReview": True, "rollbackRequired": True}}


