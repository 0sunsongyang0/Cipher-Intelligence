def _analyze_gtfobins(payload: dict[str, Any]) -> dict[str, Any]:
    commands = _string_list(payload.get("commands"), limit=300)
    matches = []
    for command in commands:
        tokens = re.findall(r"[A-Za-z0-9_.+-]+", command.casefold())
        binary = next((token for token in tokens if token in GTFO_BINARIES), None)
        if binary:
            elevated = bool(re.search(r"(?:^|\s)sudo\s", command)) or "suid" in command.casefold()
            matches.append({"binary": binary, "capabilities": list(GTFO_BINARIES[binary]), "command": command,
                            "elevatedContext": elevated, "severity": "high" if elevated else "medium",
                            "investigationPivots": ["sudo 日志", "父进程与 TTY", "执行用户与文件权限"]})
    return {"upstream": "GTFOBins/GTFOBins.github.io@acd524623f9c", "matches": matches,
            "matchCount": len(matches), "requiresHumanReview": True}


