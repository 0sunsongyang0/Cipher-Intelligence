def _safe_identifier(value: str, prefix: str = "cipher_rule") -> str:
    normalized = re.sub(r"[^A-Za-z0-9_]", "_", value.strip())
    normalized = re.sub(r"_+", "_", normalized).strip("_")
    if not normalized: normalized = prefix
    if normalized[0].isdigit(): normalized = f"{prefix}_{normalized}"
    return normalized[:80]


def _string_list(value: Any, *, limit: int = 100) -> list[str]:
    if not isinstance(value, list):
        raise HTTPException(status_code=422, detail="Skill 输入必须是数组")
    return [str(item).strip() for item in value[:limit] if str(item).strip()]


def _build_sigma(payload: dict[str, Any]) -> dict[str, Any]:
    indicators = _string_list(payload.get("indicators"))
    if not indicators: raise HTTPException(status_code=422, detail="至少需要一个检测指标")
